const HEADING_RE = /<h([23])((?:\s+[^<>]*)?)>([\s\S]*?)<\/h\1>/gi;
const ID_RE = /\bid\s*=\s*"[^"]*"/i;
export const TOC_MARKER_RE = /<div[^>]*\bclass="[^"]*\bblog-toc-marker\b[^"]*"[^>]*><\/div>/gi;

function stripTags(html: string): string {
  return html.replace(/<[^>]+>/g, "").replace(/&amp;/g, "&").replace(/&#39;|&apos;/g, "'").replace(/&quot;/g, '"').trim();
}

function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, "")
    .trim()
    .replace(/\s+/g, "-")
    .slice(0, 80);
}

function escapeHtmlText(text: string): string {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

type TocItem = { id: string; text: string; level: 2 | 3 };

// Reuses the exact utility classes already present (and so already
// generated by Tailwind's content scan) elsewhere in BlogPostArticle.tsx,
// since this markup is injected into already-sanitized HTML at render
// time rather than authored through React -- there's no component tree
// for Tailwind to see these classes in otherwise.
function renderTocNav(items: TocItem[]): string {
  const links = items
    .map(
      (item) =>
        `<li class="${item.level === 3 ? "ml-4" : ""}"><a href="#${item.id}" class="text-ink underline decoration-ink/30 underline-offset-2 hover:decoration-ink">${escapeHtmlText(item.text)}</a></li>`
    )
    .join("");
  return (
    `<nav aria-label="Table of contents" class="not-prose my-8 rounded-2xl border border-line bg-paper-soft p-5">` +
    `<h2 class="font-display text-sm font-semibold uppercase tracking-wide text-ink-soft">On this page</h2>` +
    `<ul class="mt-3 space-y-1.5 text-sm">${links}</ul></nav>`
  );
}

/** Injects an id on every H2/H3 (for anchor links, keeping any id a
 * heading already has) and, where the author explicitly dropped a Table
 * of Contents block (via the editor's toolbar button -- a
 * `blog-toc-marker` div), replaces it with a rendered nav listing every
 * H2/H3 in the post. The nav reflects the post's actual headings at
 * render time, so it can't drift out of sync the way a TOC typed out by
 * hand could -- but it only appears where the author chose to put it,
 * not automatically. Below 3 headings the marker is removed rather than
 * left as an empty box: not worth a nav for one or two sections. */
export function buildTableOfContents(html: string): string {
  const items: TocItem[] = [];
  const used = new Set<string>();

  const withIds = html.replace(HEADING_RE, (full, level, attrs: string, inner: string) => {
    const text = stripTags(inner);
    if (!text) return full;

    let id: string;
    const existing = attrs.match(ID_RE);
    if (existing) {
      id = existing[0].replace(/^id\s*=\s*"|"$/g, "");
    } else {
      const base = slugify(text) || `section-${items.length + 1}`;
      id = base;
      let n = 2;
      while (used.has(id)) id = `${base}-${n++}`;
    }
    used.add(id);
    items.push({ id, text, level: Number(level) as 2 | 3 });

    if (existing) return full;
    return `<h${level}${attrs} id="${id}">${inner}</h${level}>`;
  });

  if (!TOC_MARKER_RE.test(withIds)) return withIds;
  TOC_MARKER_RE.lastIndex = 0;

  const nav = items.length >= 3 ? renderTocNav(items) : "";
  return withIds.replace(TOC_MARKER_RE, nav);
}
